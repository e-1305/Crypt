/**
 * Hook 3: traceability table (task -> commit -> test) from .kiro/specs/<spec>/tasks.md checkbox state.
 *
 *   tsx scripts/hooks/kiro-trace.ts [spec ...]            print the table (read only)
 *   tsx scripts/hooks/kiro-trace.ts --write [spec ...]    replace the generated block in docs/KIRO.md
 *
 * Commit = the commit that first added the ticked line ("- [x] <id>") to tasks.md; open tasks show "open",
 * ticked but uncommitted tasks show "uncommitted". Test = the first backticked path under tests/ or the first
 * `npm run ...` command in the task text, else "n/a". Output is deterministic, so a second run changes nothing.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const BEGIN = "<!-- kiro-trace:begin (generated by scripts/hooks/kiro-trace.ts; edit tasks.md, not this block) -->";
export const END = "<!-- kiro-trace:end -->";

export interface Task {
  id: string;
  done: boolean;
  text: string;
}

const TASK = /^\s*- \[( |x)\] (\S+?)\.?\s+(.*)$/;

export function parseTasks(md: string): Task[] {
  const tasks: Task[] = [];
  for (const line of md.split("\n")) {
    const m = TASK.exec(line);
    if (m) tasks.push({ done: m[1] === "x", id: m[2]!, text: m[3]! });
  }
  return tasks;
}

export function testOf(text: string): string {
  const ticks = [...text.matchAll(/`([^`]+)`/g)].map((m) => m[1]!);
  const file = ticks.find((t) => /^tests\/\S+\.test\.ts$/.test(t));
  if (file) return `\`${file}\``;
  const npm = ticks.find((t) => /^npm run \S+/.test(t));
  return npm ? `\`${npm}\`` : "n/a";
}

const cell = (s: string) => s.replace(/\|/g, "\\|");
const short = (s: string) => (s.length > 70 ? `${s.slice(0, 67)}...` : s);

/** Table rows for one spec. `commitOf(line)` returns the short hash that added the ticked line, or "". */
export function renderSpec(spec: string, tasks: Task[], commitOf: (done: Task) => string): string {
  const rows = tasks.map((t) => {
    const commit = t.done ? commitOf(t) || "uncommitted" : "open";
    return `| ${cell(t.id)} ${cell(short(t.text.replace(/`/g, "")))} | ${commit === "open" || commit === "uncommitted" ? commit : `\`${commit}\``} | ${testOf(t.text)} |`;
  });
  return [`### ${spec}`, "| Task | Commit | Test |", "|---|---|---|", ...rows].join("\n");
}

function gitCommit(root: string, file: string, t: Task): string {
  try {
    const out = execFileSync("git", ["log", "--format=%h", "--reverse", "-S", `- [x] ${t.id}`, "--", file], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return out.split("\n")[0]!.trim();
  } catch {
    return "";
  }
}

export function build(root: string, specs: string[]): string {
  const dir = join(root, ".kiro", "specs");
  const names = (specs.length ? specs : readdirSync(dir)).filter((s) => existsSync(join(dir, s, "tasks.md"))).sort();
  const blocks = names.map((s) => {
    const rel = join(".kiro", "specs", s, "tasks.md");
    const tasks = parseTasks(readFileSync(join(root, rel), "utf8"));
    return renderSpec(s, tasks, (t) => gitCommit(root, rel, t));
  });
  return [BEGIN, ...blocks.flatMap((b) => [b, ""]), END].join("\n");
}

/** Replace the generated block (or append it under the traceability heading) and return the new document. */
export function splice(doc: string, block: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a >= 0 && b > a) return doc.slice(0, a) + block + doc.slice(b + END.length);
  return `${doc.replace(/\n*$/, "\n")}\n${block}\n`;
}

function main(argv: string[]): number {
  const write = argv.includes("--write");
  const specs = argv.filter((a) => !a.startsWith("--"));
  const root = resolve(import.meta.dirname, "..", "..");
  const block = build(root, specs);
  if (!write) {
    console.log(block);
    return 0;
  }
  const docPath = join(root, "docs", "KIRO.md");
  const before = readFileSync(docPath, "utf8");
  const after = splice(before, block);
  if (after === before) {
    console.log("kiro-trace: docs/KIRO.md already up to date");
  } else {
    writeFileSync(docPath, after);
    console.log("kiro-trace: updated docs/KIRO.md");
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) process.exit(main(process.argv.slice(2)));
