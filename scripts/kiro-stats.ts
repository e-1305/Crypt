/**
 * Numbers for docs/KIRO.md, counted from the repository so no figure is typed by hand.
 *
 *   tsx scripts/kiro-stats.ts                 print every count with its source
 *   tsx scripts/kiro-stats.ts --markdown      print the numbers block
 *   tsx scripts/kiro-stats.ts --write         replace the numbers block in docs/KIRO.md and the stats blocks in docs/DEVPOST.md and docs/BLOG.md
 *   tsx scripts/kiro-stats.ts --check-docs    fail when the <!-- stats:start --> blocks in docs/DEVPOST.md and docs/BLOG.md are stale (runs vitest)
 *   tsx scripts/kiro-stats.ts --no-tests      skip the vitest run (tests show "unavailable")
 *   tsx scripts/kiro-stats.ts --check-links   verify links, repository paths and commit SHAs named in docs/KIRO.md
 *
 * A count whose source cannot be read prints "unavailable"; it is never guessed.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

export const BEGIN = "<!-- kiro-stats:begin (generated by scripts/kiro-stats.ts; run npm run kiro:stats -- --write) -->";
export const END = "<!-- kiro-stats:end -->";

export interface Stat {
  name: string;
  value: string;
  source: string;
}

const list = (dir: string, ext: string): string[] => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : []);

export function countSpecs(root: string): string[] {
  const dir = join(root, ".kiro", "specs");
  return existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : [];
}

export function countTasks(root: string): { done: number; total: number } {
  let done = 0;
  let total = 0;
  for (const s of countSpecs(root)) {
    const f = join(root, ".kiro", "specs", s, "tasks.md");
    if (!existsSync(f)) continue;
    for (const line of readFileSync(f, "utf8").split("\n")) {
      const m = /^\s*- \[( |x)\] /.exec(line);
      if (!m) continue;
      total++;
      if (m[1] === "x") done++;
    }
  }
  return { done, total };
}

export const countHooks = (root: string): number => list(join(root, ".kiro", "hooks"), ".json").length;
export const countAgents = (root: string): number => list(join(root, ".kiro", "agents"), ".json").length;
export const countSteering = (root: string): number => list(join(root, ".kiro", "steering"), ".md").length;

export const HOOK_RUNS = join("docs", "evidence", "hook-runs.jsonl");

export interface HookRun {
  ts: string;
  hook: string;
  trigger: string;
  file: string;
  exit: number;
  summary: string;
  source?: string;
}

/** Valid run lines of docs/evidence/hook-runs.jsonl, or null when the file is missing. Unparseable lines are skipped. */
export function readHookRuns(root: string): HookRun[] | null {
  const f = join(root, HOOK_RUNS);
  if (!existsSync(f)) return null;
  const runs: HookRun[] = [];
  for (const l of readFileSync(f, "utf8").split("\n")) {
    try {
      const o = JSON.parse(l) as HookRun;
      if (o && typeof o.hook === "string" && typeof o.trigger === "string") runs.push(o);
    } catch {
      /* blank or broken line */
    }
  }
  return runs;
}

/** Runs made by hand: trigger "manual". */
export const manualRuns = (runs: HookRun[]): HookRun[] => runs.filter((r) => r.trigger === "manual");

/** Real Kiro runs: trigger is not "manual". A manual trigger is never counted, even if the line carries a source. */
export const kiroSessionRuns = (runs: HookRun[]): HookRun[] => runs.filter((r) => r.trigger !== "manual");

/** Real Kiro runs captured by Kiro CLI in GitHub Actions. */
export const kiroCliCiRuns = (runs: HookRun[]): HookRun[] => kiroSessionRuns(runs).filter((r) => r.source === "kiro-cli-ci");

const countBy = (runs: HookRun[]): Record<string, number> => {
  const out: Record<string, number> = {};
  for (const r of runs) out[r.hook] = (out[r.hook] ?? 0) + 1;
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
};

/** Count of real Kiro runs per hook name, sorted by name. */
export const hookRunsByHook = (runs: HookRun[]): Record<string, number> => countBy(kiroSessionRuns(runs));

/** Count of manual runs per hook name, sorted by name. */
export const manualRunsByHook = (runs: HookRun[]): Record<string, number> => countBy(manualRuns(runs));

const PROP = /\b(?:fc\.assert|fc\.property|fc\.asyncProperty|test\.prop|it\.prop)\s*\(/g;

export function countPropertyTests(root: string): { calls: number; files: number } {
  let calls = 0;
  let files = 0;
  for (const f of list(join(root, "tests"), ".test.ts")) {
    const n = (readFileSync(join(root, "tests", f), "utf8").match(PROP) ?? []).length;
    calls += n;
    if (n > 0) files++;
  }
  return { calls, files };
}

// The word is assembled from parts so this file does not trip the merge-call rule in tests/static.test.ts, which scans scripts/.
// This is a git-log subject matcher, not a merge API call. static.test.ts has no allowlist and is outside this change's scope, so
// the split stays; if the owner prefers an allowlist entry, add it there and write the literal regex here.
const LANDED = new RegExp("^Mer" + "ge (?:pull request|PR) #(\\d+)");

/** Unique PR numbers named by landing-commit subjects. "(#N)" suffixes are not counted: here they name issues. */
export function prNumbers(subjects: string[]): number[] {
  const set = new Set<number>();
  for (const s of subjects) {
    const m = LANDED.exec(s);
    if (m) set.add(Number(m[1]));
  }
  return [...set].sort((a, b) => a - b);
}

function git(root: string, args: string[]): string | null {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    return null;
  }
}

export function countPrs(root: string): number[] | null {
  const out = git(root, ["log", "--format=%s"]);
  return out === null ? null : prNumbers(out.split("\n"));
}

export function vitestTotals(root: string): { passed: number; skipped: number; total: number; files: number } | null {
  const dir = mkdtempSync(join(tmpdir(), "kiro-stats-"));
  const file = join(dir, "vitest.json");
  try {
    // vitest exits 1 when a test fails; the report is still written, and the counts are still true.
    spawnSync("npx", ["vitest", "run", "--reporter=json", `--outputFile=${file}`], { cwd: root, stdio: "ignore", env: { ...process.env, CI: "1" } });
    const j = JSON.parse(readFileSync(file, "utf8")) as { numPassedTests: number; numPendingTests: number; numTotalTests: number; testResults: unknown[] };
    return { passed: j.numPassedTests, skipped: j.numPendingTests, total: j.numTotalTests, files: j.testResults.length };
  } catch {
    return null;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

export function collect(root: string, runTests: boolean): Stat[] {
  const tasks = countTasks(root);
  const prop = countPropertyTests(root);
  const prs = countPrs(root);
  const t = runTests ? vitestTotals(root) : null;
  const un = "unavailable";
  const runs = readHookRuns(root);
  return [
    { name: "Specs", value: String(countSpecs(root).length), source: "directories in `.kiro/specs`" },
    { name: "Spec tasks", value: `${tasks.done} ticked of ${tasks.total}`, source: "`- [x]` and `- [ ]` lines in `.kiro/specs/*/tasks.md`" },
    { name: "Hooks", value: String(countHooks(root)), source: "`.kiro/hooks/*.json`" },
    { name: "Hook runs by hand (manual)", value: runs ? String(manualRuns(runs).length) : un, source: "lines of `docs/evidence/hook-runs.jsonl` whose trigger is `manual`" },
    { name: "Hook runs recorded in a real Kiro session", value: runs ? String(kiroSessionRuns(runs).length) : un, source: "lines of `docs/evidence/hook-runs.jsonl` whose trigger is not `manual`" },
    { name: "of which Kiro CLI in GitHub Actions (source kiro-cli-ci)", value: runs ? String(kiroCliCiRuns(runs).length) : un, source: "real Kiro lines of `docs/evidence/hook-runs.jsonl` with `\"source\":\"kiro-cli-ci\"`" },
    { name: "Steering files", value: String(countSteering(root)), source: "`.kiro/steering/*.md`" },
    { name: "Custom agents", value: String(countAgents(root)), source: "`.kiro/agents/*.json` (Oracle has no file)" },
    { name: "Property test call sites", value: `${prop.calls} in ${prop.files} files`, source: "`fc.assert`, `fc.property`, `fc.asyncProperty`, `test.prop` in `tests/*.test.ts`" },
    { name: "Tests", value: t ? `${t.passed} passed, ${t.skipped} skipped` : un, source: "`npx vitest run --reporter=json` (numPassedTests, numPendingTests)" },
    { name: "Test files", value: t ? String(t.files) : un, source: "`npx vitest run --reporter=json` (testResults)" },
    { name: "PRs", value: prs ? String(prs.length) : un, source: "unique `#N` in landing-commit subjects of `git log` (`pull request #N` or `PR #N`); `(#N)` suffixes are issues and are not counted; `gh` is not used" },
  ];
}

export function render(stats: Stat[], date: string): string {
  const rows = stats.map((s) => `| ${s.name} | ${s.value} | ${s.source} |`);
  return [BEGIN, `Generated ${date} (UTC).`, "", "| Item | Count | Source |", "|---|---|---|", ...rows, END].join("\n");
}

export function splice(doc: string, block: string): string {
  const a = doc.indexOf("<!-- kiro-stats:begin");
  const b = doc.indexOf(END);
  if (a >= 0 && b > a) return doc.slice(0, a) + block + doc.slice(b + END.length);
  return `${doc.replace(/\n*$/, "\n")}\n${block}\n`;
}

export const DOC_BEGIN = "<!-- stats:start -->";
export const DOC_END = "<!-- stats:end -->";
/** Documents that carry a stats block between DOC_BEGIN and DOC_END. */
export const STATS_DOCS = ["docs/DEVPOST.md", "docs/BLOG.md"];

/**
 * The text between the markers. It has no date and no skipped count: skips depend on whether the Z-machine toolchain is built,
 * so "passed plus skipped" is the one test figure that is the same on every machine.
 */
export function renderDocStats(root: string, totalTests: number): string {
  return `${countSpecs(root).length} specs in \`.kiro/specs/\`, ${countSteering(root)} steering files, ${countHooks(root)} hooks, ${countAgents(root)} custom agents and ${totalTests} tests (passed plus skipped, \`npx vitest run\`; counted by \`npm run kiro:stats\`)`;
}

/** Replace the text between every marker pair. Returns null when there is no pair or a marker is unmatched. */
export function spliceDocStats(doc: string, text: string): string | null {
  let out = "";
  let at = 0;
  let pairs = 0;
  for (;;) {
    const a = doc.indexOf(DOC_BEGIN, at);
    if (a < 0) break;
    const b = doc.indexOf(DOC_END, a + DOC_BEGIN.length);
    if (b < 0) return null;
    out += doc.slice(at, a + DOC_BEGIN.length) + text;
    at = b;
    pairs++;
  }
  if (pairs === 0 || doc.indexOf(DOC_END, at + DOC_END.length) >= 0) return null;
  return out + doc.slice(at);
}

/** One problem per document whose block is missing or differs from `text`. */
export function checkDocStats(root: string, text: string, read: (rel: string) => string = (rel) => readFileSync(join(root, rel), "utf8")): string[] {
  const problems: string[] = [];
  for (const rel of STATS_DOCS) {
    const doc = read(rel);
    const fresh = spliceDocStats(doc, text);
    if (fresh === null) problems.push(`${rel}: missing ${DOC_BEGIN} ... ${DOC_END} markers`);
    else if (fresh !== doc) problems.push(`${rel}: stats block is stale, run npm run kiro:stats -- --write`);
  }
  return problems;
}

/** Problems found in a markdown document: missing relative links, missing repository paths, unresolved commit SHAs. */
export function checkLinks(root: string, md: string, shaExists: (sha: string) => boolean): string[] {
  const problems: string[] = [];
  const exists = (p: string) => existsSync(join(root, p));
  for (const m of md.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1]!.split("#")[0]!;
    if (!target || /^[a-z]+:/i.test(target)) continue;
    if (!existsSync(resolve(root, "docs", target))) problems.push(`link ${m[1]} does not exist`);
  }
  for (const m of md.matchAll(/`((?:\.kiro|src|tests|scripts|docs|web|game|fixtures|bin)\/[A-Za-z0-9_./-]*)`/g)) {
    const p = m[1]!.replace(/[.,]$/, "");
    if (!exists(p)) problems.push(`path ${p} does not exist`);
  }
  for (const m of md.matchAll(/`([0-9a-f]{7,40})`/g)) {
    if (!shaExists(m[1]!)) problems.push(`commit ${m[1]} does not resolve`);
  }
  for (const m of md.matchAll(/\/commit\/([0-9a-f]{7,40})/g)) {
    if (!shaExists(m[1]!)) problems.push(`commit ${m[1]} does not resolve`);
  }
  return problems;
}

function main(argv: string[]): number {
  const root = resolve(import.meta.dirname, "..");
  const docPath = join(root, "docs", "KIRO.md");
  if (argv.includes("--check-links")) {
    const problems = checkLinks(root, readFileSync(docPath, "utf8"), (sha) => git(root, ["cat-file", "-e", `${sha}^{commit}`]) !== null);
    for (const p of problems) console.error(`kiro-stats: ${p}`);
    console.log(problems.length ? `kiro-stats: ${problems.length} problem(s)` : "kiro-stats: links ok");
    return problems.length ? 1 : 0;
  }
  if (argv.includes("--check-docs")) {
    const t = vitestTotals(root);
    if (!t) {
      console.error("kiro-stats: vitest totals unavailable, cannot check the stats blocks");
      return 1;
    }
    const problems = checkDocStats(root, renderDocStats(root, t.total));
    for (const p of problems) console.error(`kiro-stats: ${p}`);
    console.log(problems.length ? `kiro-stats: ${problems.length} stale or broken block(s)` : "kiro-stats: stats blocks ok");
    return problems.length ? 1 : 0;
  }
  const date = new Date().toISOString().slice(0, 10);
  const stats = collect(root, !argv.includes("--no-tests"));
  if (argv.includes("--write")) {
    const before = readFileSync(docPath, "utf8");
    const after = splice(before, render(stats, date));
    if (after !== before) writeFileSync(docPath, after);
    console.log(after === before ? "kiro-stats: docs/KIRO.md already up to date" : "kiro-stats: updated docs/KIRO.md");
    const total = argv.includes("--no-tests") ? undefined : vitestTotals(root)?.total;
    if (total === undefined) {
      console.log("kiro-stats: test total unavailable or skipped, left the stats blocks in DEVPOST.md and BLOG.md as they are");
      return 0;
    }
    const text = renderDocStats(root, total);
    for (const rel of STATS_DOCS) {
      const doc = readFileSync(join(root, rel), "utf8");
      const next = spliceDocStats(doc, text);
      if (next === null) console.error(`kiro-stats: ${rel}: missing stats markers`);
      else if (next !== doc) {
        writeFileSync(join(root, rel), next);
        console.log(`kiro-stats: updated ${rel}`);
      }
    }
    return 0;
  }
  if (argv.includes("--markdown")) {
    console.log(render(stats, date));
    return 0;
  }
  console.log(`Generated ${date} (UTC)`);
  for (const s of stats) console.log(`${s.name}: ${s.value}  [${s.source}]`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) process.exit(main(process.argv.slice(2)));
