/**
 * Timeline image for docs/KIRO.md, drawn from git history so no date is typed by hand.
 *
 *   tsx scripts/kiro-timeline.ts          write docs/img/kiro-timeline.svg
 *   tsx scripts/kiro-timeline.ts --write  same
 *   tsx scripts/kiro-timeline.ts --check  exit 1 when the file is stale
 *
 * Spec date: earliest commit that touches .kiro/specs/<name>/. Merge date: date of a landing commit named by prNumbers.
 * The end of the axis is the date of HEAD, not the wall clock, so a second run changes nothing.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { prNumbers } from "./kiro-stats.js";

export const OUT = join("docs", "img", "kiro-timeline.svg");

export type Run = (args: string[]) => string | null;

export const gitRunner = (root: string): Run => (args) => {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  } catch {
    return null;
  }
};

export interface Spec { name: string; date: string }
export interface Merge { pr: number; date: string }
export interface Timeline { start: string; end: string; days: number; specs: Spec[]; merges: Merge[] }

/** Earliest commit date (YYYY-MM-DD) of each spec directory. A spec with no commit yet is left out. */
export function specDates(root: string, run: Run = gitRunner(root)): Spec[] {
  const dir = join(root, ".kiro", "specs");
  if (!existsSync(dir)) return [];
  const out: Spec[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    const log = run(["log", "--format=%ad", "--date=short", "--", `.kiro/specs/${e.name}`]);
    const dates = (log ?? "").split("\n").filter(Boolean).sort();
    if (dates[0]) out.push({ name: e.name, date: dates[0] });
  }
  return out.sort((a, b) => a.date.localeCompare(b.date) || a.name.localeCompare(b.name));
}

/** Landing commits as "date TAB subject" lines, to PR number and date (first line seen for a number wins). */
export function landingDates(lines: string[]): Merge[] {
  const seen = new Map<number, string>();
  for (const line of lines) {
    const [date, ...rest] = line.split("\t");
    for (const pr of prNumbers([rest.join("\t")])) if (date && !seen.has(pr)) seen.set(pr, date);
  }
  return [...seen].map(([pr, date]) => ({ pr, date })).sort((a, b) => a.pr - b.pr);
}

export const dayNumber = (iso: string): number => Math.round(Date.UTC(+iso.slice(0, 4), +iso.slice(5, 7) - 1, +iso.slice(8, 10)) / 86400000);
export const isoOf = (day: number): string => new Date(day * 86400000).toISOString().slice(0, 10);

export function buildTimeline(root: string, run: Run = gitRunner(root)): Timeline | null {
  const specs = specDates(root, run);
  const head = (run(["log", "-1", "--format=%ad", "--date=short"]) ?? "").trim();
  if (!specs.length || !head) return null;
  const merges = landingDates((run(["log", "--format=%ad%x09%s", "--date=short"]) ?? "").split("\n"));
  const start = specs[0]!.date;
  const end = head > start ? head : start;
  return { start, end, days: dayNumber(end) - dayNumber(start) + 1, specs, merges };
}

export const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");

export function renderTimeline(t: Timeline): string {
  const W = 1000, L = 40, R = 960, GAP = 16, CH = 8;
  const d0 = dayNumber(t.start), span = Math.max(1, dayNumber(t.end) - d0);
  const xOf = (iso: string): number => Math.round(L + ((dayNumber(iso) - d0) / span) * (R - L));
  const labelH = Math.max(...t.specs.map((s) => s.name.length)) * CH + 14;
  const axisY = 56 + labelH;
  const perDay = new Map<string, number>();
  for (const m of t.merges) perDay.set(m.date, (perDay.get(m.date) ?? 0) + 1);
  const maxPerDay = Math.max(1, ...perDay.values());
  const H = axisY + 40 + maxPerDay * 6 + 56;
  const title = `Kiro timeline: ${t.specs.length} specs and ${t.merges.length} merged PRs in ${t.days} days, ${t.start} to ${t.end}`;
  const o: string[] = [];
  o.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-labelledby="t d">`);
  o.push(`  <title id="t">${esc(title)}</title>`);
  o.push(`  <desc id="d">Spec markers above a day axis, one per .kiro/specs folder, placed on the date of its first commit. Bars below the axis count pull requests merged each day. Generated by npm run kiro:timeline from git log.</desc>`);
  o.push(`  <style>
    .bg { fill: #ffffff; } .ax { stroke: #334155; stroke-width: 2; } .lead { stroke: #94a3b8; stroke-width: 1; }
    .tx { fill: #0f172a; font-family: system-ui, -apple-system, "Segoe UI", sans-serif; font-size: 14px; }
    .h { font-weight: bold; font-size: 16px; } .mk { fill: #1d4ed8; } .pr { fill: #047857; }
    @media (prefers-color-scheme: dark) {
      .bg { fill: #0b1220; } .ax { stroke: #cbd5e1; } .lead { stroke: #64748b; } .tx { fill: #f1f5f9; } .mk { fill: #60a5fa; } .pr { fill: #34d399; }
    }
  </style>`);
  o.push(`  <rect class="bg" x="0" y="0" width="${W}" height="${H}"/>`);
  o.push(`  <text class="tx h" x="${L}" y="28">${esc(`${t.days} days, ${t.specs.length} specs, ${t.merges.length} merged PRs`)}</text>`);
  o.push(`  <line class="ax" x1="${L}" y1="${axisY}" x2="${R}" y2="${axisY}"/>`);
  const MAXX = W - 20;
  const tops = t.specs.map((s) => xOf(s.date));
  const lxs: number[] = [];
  let prev = L - GAP;
  for (const tx of tops) { prev = Math.max(tx, prev + GAP); lxs.push(prev); }
  // Pull labels back left so a cluster on the last day stays inside the canvas.
  let next = MAXX + GAP;
  for (let i = lxs.length - 1; i >= 0; i--) { next = Math.min(lxs[i]!, next - GAP); lxs[i] = next; }
  t.specs.forEach((s, i) => {
    const tx = tops[i]!, lx = lxs[i]!;
    o.push(`  <line class="lead" x1="${tx}" y1="${axisY}" x2="${lx}" y2="${axisY - 10}"/>`);
    o.push(`  <circle class="mk" cx="${tx}" cy="${axisY}" r="4"/>`);
    o.push(`  <text class="tx" transform="translate(${lx + 5} ${axisY - 16}) rotate(-90)">${esc(s.name)}</text>`);
  });
  for (const [date, n] of [...perDay].sort()) {
    o.push(`  <rect class="pr" x="${xOf(date) - 3}" y="${axisY + 10}" width="6" height="${n * 6}"/>`);
  }
  const step = Math.max(1, Math.ceil(span / 6));
  const ticks = new Set<number>([0, span]);
  for (let i = 0; i < span; i += step) if (span - i >= step / 2) ticks.add(i);
  for (const i of [...ticks].sort((a, b) => a - b)) {
    const iso = isoOf(d0 + i), x = xOf(iso);
    o.push(`  <text class="tx" x="${x}" y="${axisY + 40 + maxPerDay * 6}" text-anchor="${i === 0 ? "start" : i === span ? "end" : "middle"}">${esc(iso)}</text>`);
  }
  o.push(`  <text class="tx" x="${L}" y="${H - 8}">Blue dot: first commit of a spec. Green bar: PRs merged that day.</text>`);
  o.push(`</svg>`);
  return o.join("\n") + "\n";
}

function main(argv: string[]): number {
  const root = resolve(import.meta.dirname, "..");
  const t = buildTimeline(root);
  if (!t) {
    console.error("kiro-timeline: no spec history in git log, cannot draw (is the clone shallow?)");
    return 1;
  }
  const svg = renderTimeline(t);
  const file = join(root, OUT);
  if (argv.includes("--check")) {
    const same = existsSync(file) && readFileSync(file, "utf8") === svg;
    console.log(same ? "kiro-timeline: up to date" : `kiro-timeline: ${OUT} is stale, run npm run kiro:timeline`);
    return same ? 0 : 1;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, svg);
  console.log(`kiro-timeline: wrote ${OUT} (${t.days} days, ${t.specs.length} specs, ${t.merges.length} PRs)`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) process.exit(main(process.argv.slice(2)));
